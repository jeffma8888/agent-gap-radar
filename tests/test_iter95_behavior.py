def test_b5_the_committed_readme_yields_no_index_violation():
    """The passing side, which is the only side the committed file can ever show."""
    assert index.index_violations(_readme(), _tracked()) == []


@pytest.mark.parametrize("omitted", index.expected_documents(index.tracked_markdown()))
def test_b5_a_readme_omitting_one_tracked_document_names_that_document(omitted):
    """The spec requires "a violation naming that document", and the COUNT is deliberately
    not pinned: the aggregate currently reports an omission twice, once as a missing row and
    once as a row naming the document zero times. Both name the omitted document and both
    call for the same repair, so requiring exactly one would pin a redundancy a later
    iteration might reasonably remove. What IS pinned is that no OTHER document is dragged
    into the report -- collateral noise is what makes a violation list unreadable.
    """
    tracked = _tracked()
    kept = [d for d in index.expected_documents(tracked) if d != omitted]
    text = _synthetic_index(kept)
    violations = index.index_violations(text, tracked)
    assert violations, f"omitting {omitted} must yield a violation"
    assert all(omitted in v for v in violations), (
        f"every violation must name {omitted}, got {violations}")
    assert any("the index names no row for it" in v for v in violations), violations


def test_b5_a_readme_naming_an_untracked_path_names_that_path():
    tracked = _tracked()
    documents = index.expected_documents(tracked)
    text = _synthetic_index([*documents, UNTRACKED_PATH])
    violations = index.index_violations(text, tracked)
    assert len(violations) == 1, f"expected exactly one violation, got {violations}"
    assert UNTRACKED_PATH in violations[0], violations
    assert "git does not track it" in violations[0], violations


def test_b5_a_readme_naming_exactly_the_tracked_set_yields_no_violation():
    tracked = _tracked()
    text = _synthetic_index(index.expected_documents(tracked))
    assert index.index_violations(text, tracked) == []


def test_b5_the_readers_are_pure_and_never_consult_the_filesystem():
    """Handed a tracked set of paths that exist NOWHERE on disk, a correct reader returns a
    clean verdict; a reader that secretly stat-ed the paths could not."""
    fictional = (SELF, "IMAGINARY.md", "nested/ALSO_IMAGINARY.md")
    text = _synthetic_index([p for p in fictional if p != SELF])
    for path in fictional:
        assert not (REPO_ROOT / path).exists() or path == SELF, (
            f"premise: {path} must not exist on disk")
    assert index.index_violations(text, fictional) == []


def test_b5_an_untracked_path_anywhere_in_the_document_is_caught_not_only_in_the_section():
    """Whole-document scope for this direction: a stale path in prose misleads a reader
    exactly as much as a stale row."""
    tracked = _tracked()
    documents = index.expected_documents(tracked)
    text = _synthetic_index(documents) + f"\n\nsee also `{UNTRACKED_PATH}` for details\n"
    violations = index.index_violations(text, tracked)
    assert [v for v in violations if UNTRACKED_PATH in v], violations


def test_b5_the_functions_take_the_tracked_set_as_an_argument():
    """A signature check, because the two-sided proofs above are only possible while the
    tracked set is injected rather than read inside each reader."""
    import inspect
    for func in (index.unnamed_documents, index.unknown_paths, index.index_violations,
                 index.provenance_violations, index.expected_documents):
        params = list(inspect.signature(func).parameters)
        assert "tracked_paths" in params, f"{func.__name__} must accept tracked_paths: {params}"
    assert list(inspect.signature(index.unresolved_paths).parameters) == ["text", "exists"]


