def test_b2_a_bare_basename_does_not_satisfy_a_nested_path():
    """`docs/CONSUMER_CONTRACT.md` CONTAINS `CONSUMER_CONTRACT.md`, so a substring reading
    would credit a row a reader cannot open from the repo root. Proved on the real nested
    documents rather than on an invented one."""
    tracked = _tracked()
    nested = [p for p in index.expected_documents(tracked) if "/" in p]
    assert nested, "premise: at least one tracked document must live in a subdirectory"
    for document in nested:
        basename_only = _synthetic_index([document.rsplit("/", 1)[1]])
        missing = index.unnamed_documents(basename_only, (SELF, document))
        assert missing == [document], (
            f"a row naming only {document.rsplit('/', 1)[1]!r} must leave {document} unnamed, "
            f"got {missing}")


def test_b2_naming_a_document_outside_the_section_does_not_count():
    """Scoped to the SECTION on purpose: a path mentioned in passing elsewhere is not an
    index row, and crediting it would let the index stay empty forever."""
    tracked = (SELF, "VISION.md")
    outside = "\n".join([
        "# synthetic",
        "",
        "prose naming VISION.md well before any index",
        "",
        INDEX_HEADING,
        "",
        "an index with no rows at all",
        "",
    ])
    assert index.unnamed_documents(outside, tracked) == ["VISION.md"]


