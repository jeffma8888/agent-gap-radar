"""Iteration 95 -- `README.md` publishes an index of every other tracked Markdown document.

WHAT THIS ITERATION CLAIMS, IN BEHAVIOURAL TERMS
`README.md` grows one section, `## Documents in this repo`, naming every other document in
`git ls-files '*.md'` by its repo-relative path with a provenance word each, and a committed
brake holds that index BOTH ways: nothing tracked goes unnamed, and no named path is untracked
or missing from disk. Nothing under `src/agent_gap_radar/` moves, so no renderer, exit code,
payload or verb surface may shift.

THE DECISION THIS MODULE RECORDS, STATED SO A LATER ITERATION DOES NOT "FIX" IT
The expectation set is DERIVED from `git ls-files`, never written down here. The consequence is
deliberate and is the whole point: when roadmap rows 64/70 eventually add `PRODUCT_ARCHIVE.md`
to the tracked set, this brake goes RED until that document gets a README row. That is the
brake working as designed, not a defect. The repair is a row in `README.md`; it is NEVER a
hard-coded list in this file, because a hard-coded list is the same artifact as the missing
README list one directory over -- it drifts the same way, and the person who would have to
update it is the person who just forgot the document.

WHY THE TWO-SIDED PROOFS ARE SYNTHETIC RATHER THAN FILE EDITS
The committed README can only ever demonstrate the PASSING side of every rule here. The rules
are therefore driven as pure functions over `(readme_text, tracked_paths)`, so a known-bad is a
string in memory instead of an edit to a tracked file that has to be put back -- and a failed
assertion cannot leave the repository dirty. One test proves that purity directly, by handing
the readers a tracked set of paths that exist nowhere on disk and requiring a clean verdict:
a reader that secretly consulted the filesystem would report those paths unresolvable.

WHAT THIS MODULE DELIBERATELY DOES NOT ASSERT
No line number, no column order, no table syntax and no wording: the index may be a table, a
list or prose, in any order, so long as each document is named by its repo-relative path with
exactly one provenance value. Two claims from the spec's acceptance criteria are NOT pinned
here and are named in `tester.md` as final-gate work, because both are assertions about SOURCE
TEXT that this station's isolation contract forbids it to read: "`git diff --stat` shows zero
lines changed under `src/agent_gap_radar/`", and the byte-for-byte comparison of renderer
stdout against its PRE-change bytes (a baseline that no longer exists once the diff is
applied). The behavioural consequence of both IS pinned, the way `test_iter30_behavior.py`
already settled for this repo: the renderers are shown to be INDEPENDENT of README content, by
running them against a register whose neighbouring README is mutated and requiring byte
equality -- a property that is testable on either branch, unlike equality with a vanished
baseline.

ISOLATION. Reads `README.md`, the tracked-file seam through `tests/_document_index.py`, and the
public CLI by RUNNING it. No network, no absolute machine path, no read of `src/`.
"""

from __future__ import annotations

import pathlib
