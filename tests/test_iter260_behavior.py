def test_b4_a_copy_holding_invalid_utf8_is_refused_rather_than_crashed(
    tmp_path, committed_bytes, rendered_bytes
):
    """A text comparison raises `UnicodeDecodeError` here: exit 1 and a multi-line traceback.

    Behavior 4 promises exit 2, zero stdout and EXACTLY ONE `Error: ` line for any changed
    byte, and iterations 258-259 spent two ships on undecodable input reaching a renderer, so
    the arm belongs in this module rather than being assumed from the four clean mutations.
    """
    copy = tmp_path / "invalid_utf8.md"
    payload = b"\xff\xfe" + committed_bytes
    copy.write_bytes(payload)
    rc, out, err = _run_door("--file", str(copy), cwd=tmp_path)
    assert rc == 2, f"an undecodable copy exited {rc}, not 2: {err[:400]!r}"
    assert out == b"", f"an undecodable copy wrote {len(out)} B to stdout: {out[:200]!r}"
    line = _sole_stderr_line(err, "invalid_utf8")
    assert str(copy) in line, f"the refusal does not name the file it read: {line!r}"
    assert REGEN_COMMAND in line, f"the refusal omits the regeneration command: {line!r}"
    assert f"committed {len(payload)} B" in line, (
        f"the refusal did not measure the undecodable copy's length: {line!r}"
    )
    assert f"rendered {len(rendered_bytes)} B" in line, (
        f"the refusal did not report the rendered length: {line!r}"
    )


