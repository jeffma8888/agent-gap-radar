@pytest.fixture(scope="module")
def git_repo_cwd(tmp_path_factory):
    """An unrelated git repository holding a decoy `REGISTER.md` and no register at all."""
    directory = tmp_path_factory.mktemp("git_repo_cwd")
    init = subprocess.run(
        ["git", "init", "-q"], cwd=str(directory), capture_output=True
    )
    (directory / "REGISTER.md").write_bytes(b"# a decoy register in another repo\n")
    return init.returncode, directory


def test_b3_the_door_ignores_a_git_repository_at_the_cwd(git_repo_cwd):
    """The poisoned plain directory cannot catch a door that resolves its root via git.

    `git rev-parse --show-toplevel` from a plain tmp directory walks UP and can still find a
    real repo, so that arm would pass for the wrong reason; inside a fresh repo of its own it
    returns that decoy, where no `gaps/` register exists. Only this arm separates the two.
    """
    init_rc, directory = git_repo_cwd
    if init_rc != 0:
        pytest.skip("git init is unavailable in this environment")
    assert (directory / ".git").is_dir(), "the decoy repository was never initialised"
    rc, out, err = _run_door(cwd=directory)
    assert rc == 0, f"the door exited {rc} inside an unrelated git repo: {err[:400]!r}"
    assert out == b"", f"the door wrote {len(out)} B to stdout inside an unrelated repo"
    assert err == b"", f"the door wrote {len(err)} B to stderr inside an unrelated repo"


