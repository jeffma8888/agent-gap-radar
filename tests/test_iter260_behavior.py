"""Iteration 260 behaviors: the register ships as a committed, generated artifact plus a
two-sided drift door.

Black-box, and the ISOLATION CONTRACT IS HONORED: nothing here reads the implementation
source, the engineer's or the reviewer's notes, `IMPLEMENTATION.patch`, or any diff. Every
expectation is a clause of `pm.md`'s six numbered Expected Behaviors, measured either by
reading the ARTIFACT'S BYTES or by RUNNING `tools/check_register_doc.py` in a real
`subprocess`. The one sweep that looks at a source file (behavior 5's "neither number is
written down anywhere") COUNTS token occurrences in `tools/*.py` and never asserts on the
code around them -- the same `rg`-shaped sweep `test_iter248_*` and iteration 259's
behavior 6 already established.

Why a real child process for the door: behavior 3 is precisely a claim about the door's
EXIT CODE and its TWO byte channels from an arbitrary working directory. An in-process
call cannot observe an exit code, and an `io.StringIO` capture cannot observe a cwd. The
child is launched with `sys.executable` -- never a `python3` that may be a wrapper shim on
the developer's PATH, which would surface as a spurious `ModuleNotFoundError` for a
runtime dep and read exactly like the cwd defect behavior 3 forbids.

Structural notes, so a green dot cannot mean less than it looks like:

* **The door is proved TWO-SIDEDLY**, as the acceptance criteria demand. Green: the tree as
  committed, from three different working directories, one of which is POISONED with a
  wrong-bytes `REGISTER.md` so a door that resolved its root from the cwd would refuse
  there. Red: four mutated copies via `--file`, plus a control copy that is byte-identical
  and must stay silent, so the refusal is attributable to the DRIFT and not to the flag.
* **One mutation is length-preserving.** A single XOR'd byte in the middle keeps both byte
  counts equal, so it is the only arm that separates a real byte comparison from a cheap
  length comparison. The appended-newline arm is the spec's own example.
* **No byte count is written down here either.** Every expected number is derived at run
  time from the artifact on disk, so this module cannot re-baseline the document and cannot
  go stale when the register grows. Iteration 259 recorded that transcribing a literal
  instead of extracting it mechanically is this seat's most expensive self-inflicted red.
* **Cost is bounded by construction** (`pm.md`'s `stage-budget: WARN` -- this seat sits at
  the 600 s cap). One in-process render, cached module-wide; ten short subprocess runs, each
  cached in a module-scoped fixture so no arm pays twice; no `radar scan`, no `copytree` of
  the 120-record register, no timing.
* **No absolute machine path and no personal identifier appears here.** The repo is located
  relative to `__file__`; every mutated copy lives under pytest's `tmp_path_factory`.
"""

from __future__ import annotations

import contextlib
import hashlib
import io
import pathlib
import re
import subprocess
import sys

import pytest

from agent_gap_radar.cli import main

#: Repo root, found relative to this file so no absolute machine path is written down.
REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]

#: Behavior 1's artifact and behavior 3-5's door, both named by `pm.md`.
ARTIFACT = REPO_ROOT / "REGISTER.md"
DOOR = REPO_ROOT / "tools" / "check_register_doc.py"
README = REPO_ROOT / "README.md"

#: The regeneration command behaviors 4 and 6 require VERBATIM. It is the published
#: command, so the artifact's provenance is reproducible by a reader with only the README.
REGEN_COMMAND = "uv run radar report . > REGISTER.md"

#: `pm.md` behavior 1: the artifact's bytes are the stdout of THIS argv, nothing else.
RENDER_ARGV = ("report", str(REPO_ROOT))

#: Behavior 1's "no added header, footer or provenance banner". Byte equality is the
#: primary proof; these phrases catch a banner that a renderer change had put in BOTH
#: sides, which equality alone would not notice.
BANNER_PHRASES = ("do not edit", "generated by", "auto-generated", "autogenerated")


def _run_door(*args, cwd):
    """Run the drift door as a real child process and return (rc, stdout, stderr) bytes."""
    proc = subprocess.run(
        [sys.executable, str(DOOR), *args],
        capture_output=True,
        cwd=str(cwd),
    )
    return proc.returncode, proc.stdout, proc.stderr


def _tracked(relative_path):
    """True when git already tracks (or has staged) `relative_path`."""
    proc = subprocess.run(
        ["git", "ls-files", "--error-unmatch", "--", relative_path],
        capture_output=True,
        cwd=str(REPO_ROOT),
    )
    return proc.returncode == 0


@pytest.fixture(scope="module")
def committed_bytes():
    """The artifact exactly as it sits in the tree, read as bytes (never decoded)."""
    return ARTIFACT.read_bytes()


@pytest.fixture(scope="module")
def rendered_bytes():
    """UTF-8 stdout of `main(["report", <repo root>])`, captured once for the module."""
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        rc = main(list(RENDER_ARGV))
    assert rc == 0, f"the render this artifact is a golden for exited {rc}, not 0"
    text = buffer.getvalue()
    assert text, "the renderer produced no stdout, so byte equality would be vacuous"
    return text.encode("utf-8")


@pytest.fixture(scope="module")
def green_arms(tmp_path_factory):
    """Behavior 3: the door with NO arguments, from three unrelated working directories.

    The third is poisoned -- it holds a `REGISTER.md` whose bytes are deliberately wrong --
    so a door that resolved the repo root (or the artifact) from the cwd refuses there.
    """
    neutral = tmp_path_factory.mktemp("neutral_cwd")
    poisoned = tmp_path_factory.mktemp("poisoned_cwd")
    (poisoned / "REGISTER.md").write_bytes(b"# not the register at all\n")
    return {
        "repo_root": (_run_door(cwd=REPO_ROOT), REPO_ROOT),
        "neutral_cwd": (_run_door(cwd=neutral), neutral),
        "poisoned_cwd": (_run_door(cwd=poisoned), poisoned),
    }


@pytest.fixture(scope="module")
def drift_arms(tmp_path_factory, committed_bytes):
    """Behaviors 4-5: four mutated copies plus one byte-identical control.

    `flipped_byte` is length-preserving on purpose: it is the only arm that distinguishes a
    byte comparison from a length comparison.
    """
    raw = committed_bytes
    flipped = bytearray(raw)
    midpoint = len(flipped) // 2
    flipped[midpoint] ^= 0x01

    mutations = {
        "appended_newline": raw + b"\n",
        "flipped_byte": bytes(flipped),
        "truncated": raw[: len(raw) // 2],
        "emptied": b"",
        "identical_control": raw,
    }

    directory = tmp_path_factory.mktemp("drift_copies")
    neutral = tmp_path_factory.mktemp("drift_cwd")
    arms = {}
    for name, data in mutations.items():
        copy = directory / f"{name}.md"
        copy.write_bytes(data)
        arms[name] = (_run_door("--file", str(copy), cwd=neutral), copy, data)
    return arms


def _sole_stderr_line(stderr, label):
    """Assert stderr is EXACTLY one newline-terminated line and return it as text."""
    assert stderr, f"{label}: stderr is empty, so the door refused silently"
    assert stderr.endswith(b"\n"), f"{label}: stderr does not end in a newline: {stderr!r}"
    body = stderr[:-1]
    assert b"\n" not in body, (
        f"{label}: stderr carries more than one line: {stderr!r}"
    )
    text = stderr.decode("utf-8")
    assert text.startswith("Error: "), f"{label}: stderr does not start with 'Error: ': {text!r}"
    return text.rstrip("\n")


