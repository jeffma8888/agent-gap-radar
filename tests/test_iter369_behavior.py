"""Iteration 369, tester-side black-box checks of the fresh-clone hotfix.

Written from the spec's Expected Behaviors only.  The README document index must
name ``docs/ROADMAP_NOTES_ARCHIVE.md`` in exactly one row (directly after the
``DIRECTIONS.md`` row, provenance ``generated by the build loop``, no
``PRODUCT.md`` token), and the iter-252 single-spelling guard must admit the
verbatim archive as a documentation site while still catching a copy of the
sentence anywhere else.

The guard is exercised behaviourally: its committed test function is imported
and run against throwaway git repositories, so this module proves that a leaked
copy in a new test module or in ``gaps/`` still reds it, rather than merely
reading the allowlist literal.
"""

from __future__ import annotations

import importlib.util
import pathlib
import subprocess

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
ROADMAP = ROOT / "PRODUCT.md"
NOTES_ARCHIVE = ROOT / "docs" / "ROADMAP_NOTES_ARCHIVE.md"
GUARD_MODULE = ROOT / "tests" / "test_iter252_behavior.py"
ARCHIVE_CELL = "`docs/ROADMAP_NOTES_ARCHIVE.md`"
PROVENANCE = "generated by the build loop"
# Assembled at runtime: spelling it whole here would make THIS module a leak site
# the moment it is committed, which is precisely the bug this iteration fixes.
SENTENCE = " ".join(("applies_when", "did", "not", "match"))
ROW_369 = ("- iter 369 hotfix: README document index names "
           "docs/ROADMAP_NOTES_ARCHIVE.md; fresh-clone test_iter95 green again")


def _text(path: pathlib.Path) -> str:
    return path.read_bytes().decode("utf-8", errors="strict")


def _index_rows() -> list[list[str]]:
    """Cells of every body row of the '## Documents in this repo' table."""
    lines = _text(README).splitlines()
    start = lines.index("## Documents in this repo")
    rows: list[list[str]] = []
    in_table = False
    for line in lines[start + 1:]:
        if line.startswith("## "):
            break
        if line.startswith("|"):
            in_table = True
            cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
            if cells and set(cells[0]) <= set("-: ") :
                continue  # separator row
            if cells[0] == "Document":
                continue  # header row
            rows.append(cells)
        elif in_table and line.strip():
            break
    assert rows, "the README document index table has no body rows"
    return rows


def _archive_row() -> list[str]:
    hits = [cells for cells in _index_rows() if cells[0] == ARCHIVE_CELL]
    assert len(hits) == 1, f"expected exactly one archive row, found {len(hits)}"
    return hits[0]


# ------------------------------------------------------------------ Behavior 1


def test_b1_index_has_exactly_one_archive_row() -> None:
    rows = _index_rows()
    named = [cells for cells in rows if ARCHIVE_CELL in cells[0]]
    assert len(named) == 1, f"archive named in {len(named)} Document cells"
    assert named[0][0] == ARCHIVE_CELL, f"Document cell is {named[0][0]!r}"


def test_b1_archive_row_sits_directly_after_directions_row() -> None:
    documents = [cells[0] for cells in _index_rows()]
    assert "`DIRECTIONS.md`" in documents, documents
    position = documents.index("`DIRECTIONS.md`")
    assert position + 1 < len(documents), "DIRECTIONS.md is the last row"
    assert documents[position + 1] == ARCHIVE_CELL, (
        f"row after DIRECTIONS.md is {documents[position + 1]!r}")


def test_b1_archive_row_provenance_is_exact() -> None:
    cells = _archive_row()
    assert len(cells) == 3, f"archive row has {len(cells)} cells: {cells!r}"
    assert cells[2] == PROVENANCE, f"provenance cell is {cells[2]!r}"
    assert cells[1], "the 'What it is' cell is empty"


def test_b1_raw_row_is_a_well_formed_three_cell_line() -> None:
    raw = [line for line in _text(README).splitlines() if ARCHIVE_CELL in line]
    assert len(raw) == 1, f"README names the archive cell on {len(raw)} lines"
    assert raw[0].startswith(f"| {ARCHIVE_CELL} | "), raw[0]
    assert raw[0].endswith(f" | {PROVENANCE} |"), raw[0]
    assert raw[0].count(" | ") == 2, raw[0]


# ------------------------------------------------------------------ Behavior 2


def test_b2_archive_row_does_not_name_the_roadmap_file() -> None:
    raw = [line for line in _text(README).splitlines() if ARCHIVE_CELL in line]
    assert len(raw) == 1, raw
    assert "PRODUCT.md" not in raw[0], raw[0]


def test_b2_roadmap_file_still_named_by_exactly_one_index_row() -> None:
    rows = _index_rows()
    naming = [cells[0] for cells in rows if "PRODUCT.md" in " | ".join(cells)]
    assert naming == ["`PRODUCT.md`"], naming


# ------------------------------------------------------------------ Behavior 3


def test_b3_archive_is_tracked_and_every_tracked_doc_file_is_indexed() -> None:
    proc = subprocess.run(["git", "ls-files", "--", "docs"], cwd=ROOT,
                          capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        pytest.skip("not a git checkout")
    tracked = {line for line in proc.stdout.splitlines() if line.endswith(".md")}
    documents = {cells[0].strip("`") for cells in _index_rows()}
    missing = sorted(tracked - documents)
    assert not missing, f"tracked docs absent from the README index: {missing!r}"


# ------------------------------------------------------------------ Behavior 4


def _guard():
    spec = importlib.util.spec_from_file_location("_iter252_guard_copy", GUARD_MODULE)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _git(repo: pathlib.Path, *args: str) -> None:
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                    "-c", "commit.gpgsign=false", *args],
                   cwd=repo, check=True, capture_output=True)


def _fake_repo(tmp_path: pathlib.Path, extra: dict[str, str]) -> pathlib.Path:
    repo = tmp_path / "repo"
    files = {
        "src/agent_gap_radar/checks.py": f'REASON = "{SENTENCE}"\n',
        "docs/CONSUMER_CONTRACT.md": f"The reason `{SENTENCE}` is documented.\n",
        "docs/ROADMAP_NOTES_ARCHIVE.md": f"# archive\n\nverbatim: {SENTENCE}\n",
        "tests/test_iter252_behavior.py": f"# {SENTENCE}\n",
        "gaps/GAP-001.json": "{}\n",
    }
    files.update(extra)
    for rel, body in files.items():
        target = repo / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(body, encoding="utf-8")
    _git(repo, "init", "-q")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "fixture")
    return repo


def test_b4_guard_admits_the_committed_archive(tmp_path, monkeypatch) -> None:
    guard = _guard()
    monkeypatch.setattr(guard, "REPO", _fake_repo(tmp_path, {}))
    guard.test_b9_the_old_sentence_is_spelled_at_exactly_one_site()


@pytest.mark.parametrize("leak", [
    "tests/test_leak_probe.py",
    "gaps/GAP-999.json",
    "docs/OTHER_NOTES.md",
    "src/agent_gap_radar/other.py",
])
def test_b4_guard_still_reds_a_copy_at_any_other_path(tmp_path, monkeypatch, leak) -> None:
    guard = _guard()
    monkeypatch.setattr(guard, "REPO", _fake_repo(tmp_path, {leak: f"x = '{SENTENCE}'\n"}))
    with pytest.raises(AssertionError):
        guard.test_b9_the_old_sentence_is_spelled_at_exactly_one_site()


def test_b4_guard_still_requires_exactly_one_checks_site(tmp_path, monkeypatch) -> None:
    guard = _guard()
    doubled = f'A = "{SENTENCE}"\nB = "{SENTENCE}"\n'
    monkeypatch.setattr(guard, "REPO", _fake_repo(
        tmp_path, {"src/agent_gap_radar/checks.py": doubled}))
    with pytest.raises(AssertionError):
        guard.test_b9_the_old_sentence_is_spelled_at_exactly_one_site()


def test_b4_guard_still_requires_the_contract_site(tmp_path, monkeypatch) -> None:
    guard = _guard()
    monkeypatch.setattr(guard, "REPO", _fake_repo(
        tmp_path, {"docs/CONSUMER_CONTRACT.md": "no reason text here\n"}))
    with pytest.raises(AssertionError):
        guard.test_b9_the_old_sentence_is_spelled_at_exactly_one_site()


def test_b4_guard_passes_on_the_live_repo() -> None:
    proc = subprocess.run(["git", "rev-parse", "--is-inside-work-tree"], cwd=ROOT,
                          capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        pytest.skip("not a git checkout")
    _guard().test_b9_the_old_sentence_is_spelled_at_exactly_one_site()


# ------------------------------------------------------------------ Behavior 5


def test_b5_archive_still_carries_the_sentence_once_and_no_readme_prose() -> None:
    text = _text(NOTES_ARCHIVE)
    assert text.count(SENTENCE) == 1, f"archive spells the sentence {text.count(SENTENCE)}x"
    row = _archive_row()
    assert row[1] not in text, "the README row prose was pasted into the verbatim archive"
    assert text.startswith("# Roadmap notes archive\n"), text[:60]
    assert text.endswith("\n") and not text.endswith("\n\n")


# ------------------------------------------------------------------ Behavior 6


def test_b6_iteration_369_row_present_once_and_short() -> None:
    lines = _text(ROADMAP).splitlines()
    assert lines.count(ROW_369) == 1, f"row present {lines.count(ROW_369)}x"
    assert len(ROW_369) <= 120, len(ROW_369)
    others = [line for line in lines if line.startswith("- iter 369 ") and line != ROW_369]
    assert not others, others
